"""
Generate audit-report.md -- a mock bias-audit deliverable in the style of a
NYC Local Law 144 audit summary. All numbers come from
artifacts/audit_results.json produced by audit.py; this script only formats.
"""

import json
import os

ROOT = os.path.dirname(os.path.abspath(__file__))
ART_DIR = os.path.join(ROOT, "artifacts")
OUT_MD = os.path.join(ROOT, "audit-report.md")

SCENARIOS = [
    ("baseline", "Baseline (single global threshold)"),
    ("threshold_tuning", "Mitigation A: per-group threshold tuning"),
    ("sample_reweighting", "Mitigation B: sample reweighting"),
]


def table_for(scenario_groups, dimension):
    lines = ["| Group | n | Selection rate | Impact ratio | PPV | 4/5 rule |",
             "|---|---|---|---|---|---|"]
    for row in scenario_groups:
        if row["dimension"] != dimension:
            continue
        status = "FAIL" if row["violates_four_fifths"] else "pass"
        ppv = f"{row['ppv']:.3f}" if row["ppv"] is not None else "n/a"
        lines.append(
            f"| {row['group']} | {row['n']} | {row['selection_rate']:.3f} | "
            f"{row['impact_ratio']:.3f} | {ppv} | {status} |"
        )
    return "\n".join(lines)


def main():
    with open(os.path.join(ART_DIR, "audit_results.json")) as f:
        res = json.load(f)
    with open(os.path.join(ROOT, "data", "generation_config.json")) as f:
        gen = json.load(f)

    scenarios = res["scenarios"]
    L = []
    A = L.append
    A("# Bias Audit Report -- Automated Resume Screening Tool (Demo)")
    A("")
    A("> **ALL DATA IN THIS REPORT IS SYNTHETIC.** It was generated by "
      "`make_data.py` for demonstration purposes. This report demonstrates "
      "audit *methodology* -- it is not a certification of any real system, "
      "and it does not satisfy any regulatory filing requirement.")
    A("")
    A("## 1. Scope")
    A("")
    A("- **System under audit:** a logistic-regression resume screener that "
      "scores applicants and advances the top 25% to interview.")
    A("- **Protected dimensions examined:** sex (gender), race/ethnicity, "
      "age band, and the sex x race/ethnicity intersections -- the "
      "dimensions NYC Local Law 144 requires in a bias audit.")
    A("- **Model inputs:** years of experience, education level, skill "
      "assessment score, referral flag, employment-gap months. "
      "Protected attributes are *not* model inputs; they are used only by "
      "the audit (which is permitted and required to see them).")
    A("- **Data:** 7,500 fully synthetic applicants (seed 42), 75/25 "
      "train/test split, test set n = "
      f"{scenarios['baseline']['summary']['n_total']}.")
    A("- **Operating point:** score threshold set so the overall selection "
      "rate is 25%.")
    A("")
    A("## 2. Methodology")
    A("")
    A("1. **Selection rate by group:** share of each protected group scoring "
      "at or above the operating threshold.")
    A("2. **Disparate impact ratio:** group selection rate divided by the "
      "highest group selection rate in that dimension. Ratios below 0.80 "
      "are flagged under the four-fifths rule.")
    A("3. **Calibration by group:** positive predictive value (PPV, "
      "precision at the operating threshold) per group, plus calibration "
      "curves (`figures/calibration_by_group.png`).")
    A("4. **Mitigation comparison:** the same metrics recomputed after "
      "(A) per-group threshold tuning and (B) sample reweighting, alongside "
      "overall accuracy and AUC so the fairness-accuracy tradeoff is visible.")
    A("")
    A("## 3. Findings -- baseline")
    A("")
    A("### By sex")
    A("")
    A(table_for(scenarios["baseline"]["groups"], "gender"))
    A("")
    A("### By race/ethnicity")
    A("")
    A(table_for(scenarios["baseline"]["groups"], "race_ethnicity"))
    A("")
    A("### By sex x race/ethnicity (intersection)")
    A("")
    A(table_for(scenarios["baseline"]["groups"], "gender_x_race"))
    A("")
    A("### By age band (control dimension -- no bias injected)")
    A("")
    A(table_for(scenarios["baseline"]["groups"], "age_band"))
    A("")
    A("**Interpretation.** The audit detects the injected bias: several "
      "groups fall below the 0.80 disparate-impact threshold. The age-band "
      "dimension, where no bias was injected, passes -- a useful sanity "
      "check that the audit flags real disparity rather than noise.")
    A("")
    A("## 4. Mitigation results")
    A("")
    A("| Scenario | Selection rate | Accuracy | AUC |")
    A("|---|---|---|---|")
    for key, label in SCENARIOS:
        s = scenarios[key]["summary"]
        A(f"| {label} | {s['selection_rate']:.3f} | {s['accuracy']:.4f} | "
          f"{s['auc']:.4f} |")
    A("")
    A("### Mitigation A -- disparate impact after per-group threshold tuning")
    A("")
    A(table_for(scenarios["threshold_tuning"]["groups"], "gender"))
    A("")
    A(table_for(scenarios["threshold_tuning"]["groups"], "race_ethnicity"))
    A("")
    A("### Mitigation B -- disparate impact after sample reweighting")
    A("")
    A(table_for(scenarios["sample_reweighting"]["groups"], "gender"))
    A("")
    A(table_for(scenarios["sample_reweighting"]["groups"], "race_ethnicity"))
    A("")
    A("**Interpretation.** Per-group threshold tuning equalizes selection "
      "rates by construction, at a small accuracy cost -- the classic "
      "fairness-accuracy tradeoff, made visible. Sample reweighting (a "
      "pre-processing fix) reduces disparity partially but does not "
      "eliminate it, because the historical labels themselves carry the "
      "injected bias and reweighting cannot fully undo that.")
    A("")
    A("## 5. Injected bias reference (synthetic ground truth)")
    A("")
    A("Documented in `make_data.py` and `data/generation_config.json`:")
    A("")
    A(f"- Direct label bias (logits): {json.dumps(gen['injected_bias']['label_bias_logit'])}")
    A(f"- Skewed referral rates: {json.dumps(gen['injected_bias']['referral_rate_by_gender_race'])} "
      f"(default {gen['injected_bias']['referral_rate_default']})")
    A("- Age band: no injected bias (control).")
    A("")
    A("## 6. Limitations")
    A("")
    A("- **Synthetic data:** findings describe the generator, not any real "
      "hiring process. Effect sizes are illustrative.")
    A("- **Single metric family:** this audit covers disparate impact and "
      "calibration only -- not equalized odds, individual fairness, or "
      "long-term feedback effects.")
    A("- **Threshold tuning is a demo technique:** deploying different "
      "cutoffs by protected class raises disparate-treatment concerns in "
      "real hiring; it is shown here to make the tradeoff measurable, not "
      "as production advice.")
    A("- **Single operating point:** results are computed at a 25% "
      "selection rate; different thresholds change the numbers.")
    A("- **Not a certification:** a real Local Law 144 audit requires an "
      "independent auditor, historical (not synthetic) data, and publication "
      "of results. This repo demonstrates the methodology an auditor would "
      "apply.")

    with open(OUT_MD, "w") as f:
        f.write("\n".join(L) + "\n")
    print(f"Wrote {OUT_MD}")


if __name__ == "__main__":
    main()
